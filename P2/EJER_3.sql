/*NOTA PERSONAL:
 * PARTE 1: SUM('COLUMNA') ES PARA VER EN QUE COLUMNA SUMAR
 * PARTE 2: 'OVER' ES PARA QUE LO HAGA EN ORDEN
 * PARTE 3: (ORDER BY 'COLUMNA') ES PARA INDICAR EL ORDEN, EN ESTE CASO LA OTRA COLUMNA
 * PARTE 4: 'AS 'INVENTARIO' INDICA EL NOMBRE UQE TENDRA LA COLUMNA DE RESULTADO
 */

CREATE TABLE SEGUIMIENTO(
	FECHA DATE NOT NULL,
	AJUSTE INT NOT NULL,
	PRIMARY KEY (FECHA, AJUSTE)
);

INSERT INTO SEGUIMIENTO(FECHA, AJUSTE)
VALUES
	('2025-01-03', 100),
    ('2025-01-04', 75),
    ('2025-01-05', -150),
    ('2025-01-06', 50),
    ('2025-01-07', -70);

SELECT 
    FECHA, 
    AJUSTE,
    SUM(AJUSTE) OVER (ORDER BY FECHA) AS INVENTARIO
FROM SEGUIMIENTO;
