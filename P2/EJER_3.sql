 * PARTE 2: REPITE LA TABLA 3 VECES PA QUE EL PROGRAMA NO EXPLOTE CON: AS t1, 2 y 3
 * PARTE 3. PARA QUE NO SE REPITA LETRA "<>" ES COMO UN IGUALN'T
 */

CREATE TABLE CASO_P(
CASO VARCHAR(10) NOT NULL,
PRIMARY KEY (CASO)
);

INSERT INTO CASO_P(CASO)
VALUES
	('A'),
	('B'),
	('C');

SELECT 
    t1.CASO AS Primero, 
    t2.CASO AS Segundo, 
    t3.CASO AS Tercero
FROM CASO_P AS t1
CROSS JOIN CASO_P AS t2
CROSS JOIN CASO_P AS t3
WHERE t1.CASO <> t2.CASO
  AND t1.CASO <> t3.CASO
  AND t2.CASO <> t3.CASO;

