/*NOTA PERSONAL:
 * PARTE 1: DATEDIFF RESTA LAS FECHAS QUE QUIERAS RESTAR
 * PARTE 2: LA PARTE DE LEAD HACE QUE LA TABLA RESTE EL NUMERO CON EL DE ABAJO SOLO SI TIENEN EL MISMO VALOR EN LA COLUMNA 'DDESARROLLO'
 * PARTE 3: WITH 'DIFERENCE' CREA UNA TABLA TEMPORAL EN LO QUE SACAMOS EL PROMEDIO
 * PARTE 4: AVG CALCULA EL PROMEDIO
 */

CREATE TABLE PROMEDIO(
	DESARROLLO VARCHAR(50) NOT NULL,
	TERMINADO DATE NOT NULL,
	PRIMARY KEY(DESARROLLO, TERMINADO)
);

INSERT INTO PROMEDIO (DESARROLLO, TERMINADO)
VALUES
	('RestAPI', '2024-06-01'),
    ('RestAPI', '2024-06-14'),
    ('RestAPI', '2024-06-15'),
    ('Web', '2024-06-01'),
    ('Web', '2024-06-02'),
    ('Web', '2024-06-19'),
    ('App', '2024-06-01'),
    ('App', '2024-05-15'),
    ('App', '2024-06-30');

WITH Diferencias AS (
    SELECT 
        DESARROLLO,
        TERMINADO,
        DATEDIFF(
            LEAD(TERMINADO) OVER (PARTITION BY DESARROLLO ORDER BY TERMINADO), 
            TERMINADO
        ) AS dias_diferencia
    FROM PROMEDIO
)
SELECT 
    DESARROLLO, 
    AVG(dias_diferencia) AS promedio_dias
FROM Diferencias
WHERE dias_diferencia IS NOT NULL
GROUP BY DESARROLLO;

