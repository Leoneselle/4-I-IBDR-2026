    SELECT 
        PROCESO, 
        MENSAJE, 
        OCURRENCIAS,
        ROW_NUMBER() OVER(PARTITION BY MENSAJE ORDER BY OCURRENCIAS DESC) as ranking
    FROM OCURRENCIAS
