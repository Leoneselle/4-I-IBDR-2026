CREATE TABLE PRECIO(
	ID_PRODUCTO INT NOT NULL,
	FECHA DATE NOT NULL,
	PRECIO DOUBLE NOT NULL,
	PRIMARY KEY (ID_PRODUCTO, FECHA)
);

